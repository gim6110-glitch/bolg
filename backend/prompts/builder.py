def normalize_area(area: str) -> str:
    try:
        return AREA_LABELS[area]
    except KeyError as exc:
        allowed = ", ".join(AREA_LABELS)
        raise ValueError(f"지원하지 않는 영역입니다: {area}. 허용값: {allowed}") from exc


def get_max_chars(area: str) -> int:
    return MAX_CHARS[normalize_area(area)]


def build_system_prompt(area: str, curriculum: Curriculum = DEFAULT_CURRICULUM) -> str:
    normalized = normalize_area(area)
    return "\n\n".join([
        COMMON_SYSTEM.strip(),
        CURRICULUM_PROMPTS[curriculum].strip(),
        AREA_PROMPTS[normalized].strip(),
        CHECKLIST.strip(),
    ])


def build_write_prompt(area: str, input_data: dict[str, Any]) -> tuple[str, str]:
    normalized = normalize_area(area)
    payload = {
        "영역": normalized,
        "최대글자수": get_max_chars(normalized),
        "입력": input_data,
    }
    system = build_system_prompt(normalized)
    user = MODE_WRITE.format(input_data=json.dumps(payload, ensure_ascii=False, indent=2)) + MODE_WRITE_SCHEMA
    return system, user


def build_review_prompt(area: str, input_text: str) -> tuple[str, str]:
    normalized = normalize_area(area)
    system = build_system_prompt(normalized)
    user = MODE_REVIEW.format(input_text=input_text) + f"\n최대글자수: {get_max_chars(normalized)}\n" + MODE_REVIEW_SCHEMA
    return system, user


def build_similarity_prompt(sentences: list[dict[str, str]]) -> str:
    return SIMILARITY_PROMPT.format(sentences=json.dumps(sentences, ensure_ascii=False, indent=2))
